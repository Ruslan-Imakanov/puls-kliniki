// Текст для диктора: как произносить аббревиатуры (в субтитрах остаётся обычное написание).
export const SAY = [
  [/EBITDA/g, 'ибитда'], [/\bCAC\b/g, 'си-эй-си'], [/\bLTV\b/g, 'эл-ти-ви'], [/\bROMI\b/g, 'роми'], [/\bFEFO\b/g, 'фифо'],
  [/ABC-анализ/g, 'эй-би-си анализ'], [/группа A\b/g, 'группа эй'], [/\bB —/g, 'би —'], [/\bC —/g, 'си —'],
  [/клавиша N\b/g, 'клавиша эн'], [/1С/g, 'один-эс'], [/«Операция»/g, '«Операция»'],
];
export const say = t => SAY.reduce((s, [a, b]) => s.replace(a, b), t);
